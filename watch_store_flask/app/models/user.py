
from datetime import datetime, timezone
from bson.objectid import ObjectId
from flask_login import UserMixin
from werkzeug.security import generate_password_hash, check_password_hash
import bcrypt
from app.db import get_db


class User(UserMixin):
    """User entity compatible with Flask-Login."""

    def __init__(self, doc):
        self._doc = doc or {}
        self.id = str(self._doc.get("_id", ""))
        self.fullName = self._doc.get("fullName", "")
        self.email = self._doc.get("email", "")
        self.password = self._doc.get("password", "")
        self.phone = self._doc.get("phone", "")
        self.address = self._doc.get("address", "")
        self.role = self._doc.get("role", "customer")
        self.isActive = self._doc.get("isActive", True)
        self.createdAt = self._doc.get("createdAt")
        self.updatedAt = self._doc.get("updatedAt")

    @property
    def is_active(self):
        return bool(self.isActive)

    @property
    def is_admin(self):
        return self.role == "admin"

    def check_password(self, password):
        if not self.password or not password:
            return False

        try:
            # Support BCrypt hashes from the existing MongoDB database.
            if self.password.startswith(("$2a$", "$2b$", "$2y$")):
                return bcrypt.checkpw(
                    password.encode("utf-8"),
                    self.password.encode("utf-8")
                )

            # Support passwords generated by Werkzeug.
            return check_password_hash(self.password, password)

        except (ValueError, TypeError):
            return False

    def to_dict(self):
        return {
            "id": self.id,
            "fullName": self.fullName,
            "email": self.email,
            "phone": self.phone,
            "address": self.address,
            "role": self.role,
            "isActive": self.isActive,
            "createdAt": self.createdAt.isoformat() if isinstance(self.createdAt, datetime) else str(self.createdAt),
        }

    # Repository static methods
    @staticmethod
    def get_collection():
        return get_db().users

    @classmethod
    def find_by_id(cls, user_id):
        try:
            doc = cls.get_collection().find_one({"_id": ObjectId(user_id)})
            return cls(doc) if doc else None
        except Exception:
            return None

    @classmethod
    def find_by_email(cls, email):
        if not email:
            return None
        doc = cls.get_collection().find_one({"email": email.strip().lower()})
        return cls(doc) if doc else None

    @classmethod
    def create(cls, fullName, email, password, phone="", address="", role="customer", is_active=True):
        hashed = generate_password_hash(password)
        now = datetime.now(timezone.utc)
        doc = {
            "fullName": fullName.strip(),
            "email": email.strip().lower(),
            "password": hashed,
            "phone": phone.strip() if phone else "",
            "address": address.strip() if address else "",
            "role": role,
            "isActive": is_active,
            "createdAt": now,
            "updatedAt": now,
        }
        res = cls.get_collection().insert_one(doc)
        doc["_id"] = res.inserted_id
        return cls(doc)

    @classmethod
    def update_profile(cls, user_id, full_name, phone, address):
        cls.get_collection().update_one(
            {"_id": ObjectId(user_id)},
            {
                "$set": {
                    "fullName": full_name.strip(),
                    "phone": phone.strip() if phone else "",
                    "address": address.strip() if address else "",
                    "updatedAt": datetime.now(timezone.utc),
                }
            },
        )
        return cls.find_by_id(user_id)

    @classmethod
    def change_password(cls, user_id, new_password):
        hashed = generate_password_hash(new_password)
        cls.get_collection().update_one(
            {"_id": ObjectId(user_id)},
            {
                "$set": {
                    "password": hashed,
                    "updatedAt": datetime.now(timezone.utc),
                }
            },
        )
        return True

    @classmethod
    def toggle_lock(cls, user_id):
        user = cls.find_by_id(user_id)
        if not user:
            return None
        new_status = not user.isActive
        cls.get_collection().update_one(
            {"_id": ObjectId(user_id)},
            {
                "$set": {
                    "isActive": new_status,
                    "updatedAt": datetime.now(timezone.utc),
                }
            },
        )
        return cls.find_by_id(user_id)

    @classmethod
    def get_all_customers(cls, search=None, page=1, per_page=10):
        query = {"role": "customer"}
        if search:
            query["$or"] = [
                {"fullName": {"$regex": search, "$options": "i"}},
                {"email": {"$regex": search, "$options": "i"}},
                {"phone": {"$regex": search, "$options": "i"}},
            ]
        total = cls.get_collection().count_documents(query)
        cursor = (
            cls.get_collection()
            .find(query)
            .sort("createdAt", -1)
            .skip((page - 1) * per_page)
            .limit(per_page)
        )
        users = [cls(doc) for doc in cursor]
        total_pages = max(1, (total + per_page - 1) // per_page)
        return users, total, total_pages
